# ── 格式校验器 ──

def validate_review_format(output: str, agent_type: str) -> list[str]:
    """代码级格式校验——qwen3.6-27b 输出质量控制

    Returns:
        list[str]: 格式问题列表，空列表表示格式合格
    """
    issues = []

    if agent_type == "dpa_round1":
        # DPA 第一轮必须包含四张表
        required_tables = [
            "★号条款",
            "资格准入条件",
            "评分标准",
            "格式与封装",
        ]
        for table_name in required_tables:
            if table_name not in output:
                issues.append(f"缺少{table_name}提取表")

    elif agent_type == "dpa_round2":
        # DPA 第二轮必须包含字段提取表
        required_sections = ["公司基本信息", "资质证书", "社保", "审计", "报价", "项目名称一致性"]
        found = sum(1 for s in required_sections if s in output)
        if found < 3:
            issues.append(f"字段提取表不完整（仅找到{found}/{len(required_sections)}类）")

    elif agent_type in ("bca", "fca"):
        # BCA/FCA 必须输出判定结果
        if "PASS" not in output and "FAIL" not in output and "合格" not in output and "不合格" not in output:
            issues.append("缺少明确的 PASS/FAIL 判定")

        # 检查是否有检查项输出（匹配 "检查项："、"检查项1："、"**检查项1：**" 等格式）
        check_count = len(re.findall(r'检查项\d*[：:]', output))
        # FCA 也可以用 PASS/FAIL/WARNING 出现次数来判定是否有足够检查项
        if agent_type == "fca" and check_count < 2:
            verdict_count = len(re.findall(r'(?:PASS|FAIL|WARNING)', output))
            if verdict_count >= 6:
                check_count = verdict_count
        if check_count < 2:
            issues.append(f"检查项数量过少（仅{check_count}个），可能遗漏审查内容")

        # BCA 特有：必须包含否决项/缺陷项汇总
        if agent_type == "bca":
            if "否决项" not in output and "缺陷项" not in output:
                issues.append("BCA 缺少否决项清单或缺陷项清单汇总")

        # FCA 特有：必须包含文件命名检查
        if agent_type == "fca":
            if "文件命名" not in output and "命名规则" not in output:
                issues.append("FCA 缺少文件命名检查")

        # 模糊用语检测（通用）
        fuzzy_terms = ["可能", "或许", "大概", "似乎"]
        found_fuzzy = [t for t in fuzzy_terms if t in output]
        if found_fuzzy:
            issues.append(f"输出包含模糊用语: {', '.join(found_fuzzy)}")

    elif agent_type == "ora":
        # ORA 报告必须包含关键章节
        required_sections = ["项目", "审查", "废标", "胜算", "隐蔽", "电子文件", "否决", "人工复核"]
        missing = [s for s in required_sections if s not in output]
        if len(missing) > 4:
            issues.append(f"报告章节严重缺失: {missing}")

        # ORA 报告必须包含投标建议
        bid_advice_terms = ["建议递交", "有条件递交", "不建议递交"]
        if not any(t in output for t in bid_advice_terms):
            issues.append("ORA 报告缺少投标建议（必须三选一）")

        # AI 痕迹检测
        ai_traces = ["根据指令手册", "按照SOP", "作为ORA", "作为BCA", "作为FCA", "作为DPA",
                     "智能体判断", "已按模板", "审查完成", "提取完毕"]
        found_traces = [t for t in ai_traces if t in output]
        if found_traces:
            issues.append(f"ORA 报告包含 AI 痕迹表述: {', '.join(found_traces)}")

    return issues


def is_format_valid(issues: list[str]) -> bool:
    if issues is None:
        return False
    return len(issues) == 0
