def _truncate(text: str, max_chars: int = 20000) -> str:
    """截断长文本（27b 适配：默认提升到 20000 字符）"""
    if not text:
        return "[无内容]"
    if len(text) <= max_chars:
        return text
    return text[:max_chars] + f"\n\n... [已截断，原文共{len(text)}字符]"


def _build_file_index(bid_docs: dict[str, str]) -> str:
    """构建投标文件索引，帮助模型了解有哪些文件存在"""
    lines = ["| 序号 | 文件名 | 提取字符数 | 文件状态说明 |",
             "|------|--------|-----------|-------------|"]
    for i, (name, content) in enumerate(bid_docs.items(), 1):
        clen = len(content)
        if clen < 50 and name.endswith('.pdf'):
            status = "扫描件PDF，文本未能提取（文件实体存在，需人工查看）"
        elif clen < 50:
            status = "文本极少（可能为空模板或扫描件）"
        elif clen > 5000:
            status = f"已提取 {clen:,} 字符（内容完整）"
        elif clen > 500:
            status = f"已提取 {clen:,} 字符（内容基本完整）"
        else:
            status = f"部分提取 {clen:,} 字符"
        lines.append(f"| {i} | {name} | {clen:,} | {status} |")
    return "\n".join(lines)


