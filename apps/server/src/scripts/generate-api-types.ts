/**
 * 按后端模块拆分生成前端 API 类型文件。
 *
 * 流程：从 Hono 实例导出完整 OpenAPI spec → 按 /api/v1/{module}/ 前缀拆分 paths →
 * 每个模块仅生成 paths 部分，components 单独生成一份共享文件 → 最后生成 api-types.d.ts 合并导出。
 *
 * 产物结构（写入 apps/client/src/api/）：
 *   components.d.ts         — 全量 components（schemas），所有模块共享
 *   {module}/{module}.d.ts  — 每个模块一份，只含该模块的 paths
 *   api-types.d.ts          — 合并所有模块 paths + re-export components，供 openapi-fetch client 使用
 */

import { writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript'
import ts from 'typescript'
import { app, apiDocumentConfig } from '../app.js'

const __dirname = dirname(fileURLToPath(import.meta.url))

// Hono 和 openapi-typescript 都使用 OpenAPI 3.1，但所用的类型定义不同。
const fullSpec = app.getOpenAPI31Document(apiDocumentConfig) as unknown as OpenAPI3

// ==================== 按 URL 前缀分组 paths ====================
// 正则提取 /api/v1/{segment}/ 中的 segment（如 auth、users）
const MODULE_REGEX = /^\/api\/v1\/([^/]+)/
const moduleMap = new Map<string, string[]>()

const specPaths = fullSpec.paths ?? {}
for (const path of Object.keys(specPaths)) {
  const match = path.match(MODULE_REGEX)
  if (!match) continue
  const segment = match[1]
  let paths = moduleMap.get(segment)
  if (!paths) {
    paths = []
    moduleMap.set(segment, paths)
  }
  paths.push(path)
}

if (moduleMap.size === 0) {
  console.log('No API paths found, skipping type generation.')
  process.exit(0)
}

// NOTE: 这里需要改为前端项目的目录
const apiDir = resolve(__dirname, '../../../client/src/api')

const generatedHeader = '// Auto-generated by generate-api-types.ts — do not edit manually\n\n'

// ==================== 生成共享 components.d.ts ====================
{
  const componentsOnlySpec: OpenAPI3 = {
    openapi: fullSpec.openapi,
    info: fullSpec.info,
    paths: {},
    components: fullSpec.components,
  }

  const ast = await openapiTS(componentsOnlySpec)
  const contents = astToString(ast)
  const outputPath = resolve(apiDir, 'components.d.ts')
  writeFileSync(outputPath, generatedHeader + contents, 'utf-8')
  console.log('Generated: components.d.ts (shared schemas)')
}

// ==================== 逐模块生成仅 paths 的 .d.ts ====================
const moduleSegments: string[] = []

for (const [segment, paths] of moduleMap) {
  moduleSegments.push(segment)

  const subPaths: NonNullable<OpenAPI3['paths']> = {}
  for (const p of paths) {
    subPaths[p] = specPaths[p]
  }

  const ast = await openapiTS({ ...fullSpec, paths: subPaths })
  // 仅替换 components 声明，保留 operationId 等生成的其他类型。
  const declarations = ast.filter((node) => !((ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.name.text === 'components'))
  const contents = astToString(declarations)

  const moduleDir = resolve(apiDir, segment)
  mkdirSync(moduleDir, { recursive: true })
  const outputPath = resolve(moduleDir, `${segment}.d.ts`)
  writeFileSync(outputPath, `${generatedHeader}import type { components } from '../components'\n\n${contents}`, 'utf-8')
  console.log(`Generated: ${segment}/${segment}.d.ts (${paths.length} path${paths.length > 1 ? 's' : ''})`)
}

// ==================== 生成 api-types.d.ts 合并导出 ====================
const indexLines: string[] = ['// Auto-generated by generate-api-types.ts — do not edit manually', '']

const imports: string[] = []
const pathMerges: string[] = []

for (const [index, segment] of moduleSegments.entries()) {
  const alias = `ModulePaths${index + 1}`
  imports.push(`import type { paths as ${alias} } from './${segment}/${segment}'`)
  pathMerges.push(alias)
}

indexLines.push(...imports)
indexLines.push('')
indexLines.push(`export type { components } from './components'`)
indexLines.push(`export type paths = ${pathMerges.join(' & ')}`)
indexLines.push('')

const indexPath = resolve(apiDir, 'api-types.d.ts')
writeFileSync(indexPath, indexLines.join('\n'), 'utf-8')
console.log(`Generated: api-types.d.ts (merging ${moduleSegments.length} module${moduleSegments.length > 1 ? 's' : ''})`)
